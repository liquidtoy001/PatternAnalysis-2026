"""Joint t-SNE of real and generated VAE features, coloured by class (local).

Real points: one training and one held-out slice per patient, coloured by
their true class. Generated points: the first 32 seeds per class of each
model, coloured by the class requested. Section 2.4 asks for this plot with
ground-truth colours; 2-D distances are not a coverage measure.

    python tools/final_tsne.py --real outputs/final-real-<job> \
        --cohorts outputs/final-cohorts-<job> --output outputs/final-tsne-<date>
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from sklearn.manifold import TSNE  # noqa: E402

MARKERS = "osvP*XD^<>ph"
COLOURS = {0: "#c8640a", 1: "#1f6fb4"}  # AD orange, NC blue


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--real", type=Path, required=True)
    parser.add_argument("--cohorts", type=Path, required=True)
    parser.add_argument("--per-class", type=int, default=32)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    real = np.load(args.real / "private-real-features.npz")
    real_report = json.loads((args.real / "report.json").read_text())
    cohorts = np.load(args.cohorts / "private-cohort-features.npz")
    listing = json.loads((args.cohorts / "private-cohorts.json").read_text())
    heldout_name = real_report["roles"]["heldout"]
    groups = [
        ("train", real["train_ref_vae"], real["train_ref_is_nc"]),
        (heldout_name, real["heldout_ref_vae"], real["heldout_ref_is_nc"]),
    ]
    for name, entry in listing.items():
        seeds = np.array(entry["seeds"])
        keep = seeds < min(seeds) + args.per_class
        groups.append(
            (name, cohorts[f"{name}_vae"][keep], cohorts[f"{name}_is_nc"][keep])
        )
    if len(groups) > len(MARKERS):
        raise ValueError(f"{len(groups)} groups but only {len(MARKERS)} marker shapes")
    features = np.concatenate([g[1] for g in groups])
    embedding = TSNE(
        n_components=2, perplexity=30, init="pca", random_state=3710
    ).fit_transform(features)
    figure, axis = plt.subplots(figsize=(10, 7.5))
    start = 0
    for marker, (name, values, is_nc) in zip(MARKERS, groups):
        points = embedding[start : start + len(values)]
        start += len(values)
        for c, label in ((0, "AD"), (1, "NC")):
            axis.scatter(
                *points[is_nc == c].T,
                marker=marker,
                c=COLOURS[c],
                s=26,
                alpha=0.75,
                label=f"{name} / {label}",
                edgecolors="none",
            )
    axis.legend(fontsize=7, ncol=2, loc="best")
    axis.set(
        title=f"Frozen VAE features: joint t-SNE ({len(features)} points)",
        xlabel="t-SNE 1",
        ylabel="t-SNE 2",
    )
    figure.text(
        0.01,
        0.01,
        "Real points coloured by true class, generated by requested class. "
        "2-D distances are not coverage measures.",
        fontsize=8,
    )
    figure.tight_layout()
    figure.savefig(args.output / "tsne.png", dpi=150)
    (args.output / "report.json").write_text(
        json.dumps(
            {
                "groups": {name: len(values) for name, values, _ in groups},
                "test_split_read": real_report["test_split_read"],
                "perplexity": 30,
                "random_state": 3710,
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
